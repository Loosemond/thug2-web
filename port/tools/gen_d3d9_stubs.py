#!/usr/bin/env python3
"""Generate port/src/d3d9/stubs.h: for each Direct3D 9 interface in the pinned d3d9.h, a class implementing every
method (its inherited ones too) as "not implemented" - logged once, then E_NOTIMPL / 0. The D3D9 layer's classes
derive from these and override what they implement, so a vtable slot the game calls by offset always exists.

    python3 -I port/tools/gen_d3d9_stubs.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / "build" / "deps" / "directx" / "d3d9.h"
OUT = ROOT / "port" / "src" / "d3d9" / "stubs.h"

INTERFACES = [
    "IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DResource9", "IDirect3DSurface9",
    "IDirect3DVolume9", "IDirect3DBaseTexture9", "IDirect3DTexture9", "IDirect3DCubeTexture9",
    "IDirect3DVolumeTexture9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9", "IDirect3DVertexDeclaration9",
    "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DStateBlock9", "IDirect3DQuery9",
]


def parse(text):
    """{interface: (base, [(return type, name, parameters)])} in declaration (vtable) order."""
    found = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\((\w+)\s*,\s*(\w+)\)\s*\{(.*?)\n\};", text, re.S):
        name, base, body = m.groups()
        methods = []
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        for mm in re.finditer(r"STDMETHOD(_)?\(\s*(?:([^,()]+?)\s*,\s*)?(\w+)\s*\)\s*\((.*?)\)\s*PURE\s*;", body, re.S):
            ret = mm.group(2).strip() if mm.group(1) else "HRESULT"
            params = " ".join(mm.group(4).split())
            params = re.sub(r"^THIS_?\s*", "", params)
            methods.append((ret, mm.group(3), params))
        found[name] = (base, methods)
    return found


def flatten(interfaces, name):
    if name == "IUnknown":
        return [("HRESULT", "QueryInterface", "REFIID riid, void** ppvObject"), ("ULONG", "AddRef", ""),
                ("ULONG", "Release", "")]
    base, methods = interfaces[name]
    own = [m for m in methods if m[1] not in ("QueryInterface", "AddRef", "Release")]
    inherited = flatten(interfaces, base)
    names = {m[1] for m in inherited}
    return inherited + [m for m in own if m[1] not in names]


def main():
    interfaces = parse(HEADER.read_text())
    out = ["#pragma once", "// Generated by port/tools/gen_d3d9_stubs.py from the pinned d3d9.h - do not edit.", "",
           "#include <d3d9.h>", "", "namespace D3D9 {", "",
           "// Logs the first call of a method the layer doesn't implement.",
           "void NotImplemented(const char* method);", ""]
    for name in INTERFACES:
        out.append(f"class Stub{name[1:]} : public {name} {{")
        out.append("public:")
        for ret, method, params in flatten(interfaces, name):
            if method in ("QueryInterface", "AddRef", "Release"):
                continue  # (every class has its own: D3D9::Object)
            if ret == "HRESULT":
                body = f'NotImplemented("{name}::{method}"); return E_NOTIMPL;'
            elif ret == "void":
                body = f'NotImplemented("{name}::{method}");'
            else:
                body = f'NotImplemented("{name}::{method}"); return {{}};'
            out.append(f"    {ret} STDMETHODCALLTYPE {method}({params}) override {{ {body} }}")
        out.append("};")
        out.append("")
    out.append("} // namespace D3D9")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(INTERFACES)} interfaces")


if __name__ == "__main__":
    main()
