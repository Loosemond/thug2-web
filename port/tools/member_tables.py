# Generates port/src/hook/member_tables.inc from upstream's headers:
#  - the six member function tables the source reads by address but never defines (method, address, script name);
#  - the member function pointers of the tables the source does define (GAME_GLOBAL g_*MemberFunctions: names and
#    component types only - in the original, static initialisers put each entry's function in).
import re, pathlib, sys
G = pathlib.Path("upstream/src/game")
T=[]
for i in range(256):
    c=i
    for _ in range(8): c = (0xEDB88320 ^ (c>>1)) if c&1 else c>>1
    T.append(c)
def crc(s):
    c=0xFFFFFFFF
    for ch in s.encode():
        if 65<=ch<=90: ch+=32
        c=(c>>8)^T[(c^ch)&0xFF]
    return c
replaces = {}
for p in G.rglob("*.cpp"):
    for m in re.finditer(r"REPLACE(?:_SOURCE_ONLY)?\((0x[0-9A-F]{8}),\s*&?([\w:]+)\)", p.read_text(errors="replace")):
        replaces[m.group(2)] = m.group(1)
decl = re.compile(r"^\s*(?:int|bool|uint32_t)\s+(\w+)\((?:Script::)?CStruct\*\s*\w*,\s*(?:Script::)?CScript\*\s*\w*\);\s*(?://\s*(.*))?$")
skip = {"InitFromStructure", "RefreshFromStructure", "CallMemberFunction", "SetParams"}
def gather(header, lo, hi, cls):
    lines = (G/header).read_text().splitlines()
    out = []
    for i in range(lo-1, min(hi, len(lines))):
        m = decl.match(lines[i])
        if not m or m.group(1) in skip: continue
        name, comment = m.group(1), m.group(2) or ""
        a = re.search(r"(0x[0-9A-F]{8})", comment)
        addr = a.group(1) if a else None
        if not addr:
            for k in range(i-1, max(i-6, 0), -1):  # an address in the comment just above
                b = re.match(r"\s*//\s*(0x[0-9A-F]{8})", lines[k])
                if b: addr = b.group(1); break
                if not lines[k].strip().startswith("//"): break
        if not addr:
            for fn, ad in replaces.items():
                if fn.endswith(cls + "::" + name): addr = ad; break
        # the script name: "(Name)" after the declaration, else "0xADDR (Name", "(the script member function Name",
        # "(checksum 0xKEY" in the comment block above (a name starts with a capital or an underscore - not "(the ...")
        j = i  # (the comment block above the declaration - and above the declarations it's one of)
        while j > 0 and decl.match(lines[j-1]): j -= 1
        k = j
        while k > 0 and lines[k-1].strip().startswith("//"): k -= 1
        above = " ".join(lines[k:j])
        check = (re.search(r"\[(0x[0-9A-F]{8})\]", comment) or re.search(r"\(checksum (0x[0-9A-F]{8})", above))
        alias = (re.search(r"\(([A-Z_]\w*|0x[0-9A-F]{8})\)", comment)
                 or re.search(r"\(the (?:script )?member function ([A-Za-z_]\w*)", above)
                 or (addr and re.search(re.escape(addr) + r"\s*\(([A-Z_]\w*|0x[0-9A-F]{8})\b", above)))
        if check: key, label = int(check.group(1), 16), check.group(1)
        elif alias and alias.group(1).startswith("0x"): key, label = int(alias.group(1), 16), alias.group(1)
        elif alias: key, label = crc(alias.group(1)), alias.group(1)
        else: key, label = crc(name), name
        if addr: out.append((key, int(addr, 16), label))
        else: print("no address:", header, name, file=sys.stderr)
    return out
def section(header, start_pat):
    lines = (G/header).read_text().splitlines()
    s = next(i for i, l in enumerate(lines) if re.search(start_pat, l)) + 1
    e = next((i for i in range(s+1, len(lines)) if re.match(r"\s*// ---", lines[i])), len(lines))
    return s, e + 1
tables = [
    ("object", 0x00683550, 0x57525413, gather("obj/object.h", *section("obj/object.h", r"// --- the member functions scripts call on the object"), "CObject")),
    ("composite", 0x00683268, 0x0ADA4E74, gather("obj/object.h", *section("obj/object.h", r"member functions scripts call .the table at 0x00683268"), "CCompositeObject")),
    ("core physics", 0x006826C8, 0x5BD63B29, gather("skater/core_physics.h", 1, 10**6, "CorePhysicsComponent")),
    ("walk", 0x006847F8, 0x726E85AA, [e for e in gather("skater/walk_physics.h", 1, 10**6, "CWalkComponent")]),
    ("vehicle camera", 0x00684150, 0x2C747D8A, gather("skater/vehicle_camera.h", 1, 10**6, "CVehicleCameraComponent")),
    ("balance trick", 0x00683238, 0x589E5FB3, gather("skater/balance_trick.h", 1, 10**6, "CSkaterBalanceTrickComponent")),
]
for name, at, typ, entries in tables:
    print(f"// {name}: {len(entries)} entries", file=sys.stderr)
    print(f"{name}|{at:#010x}|{typ if typ is None else hex(typ)}|" + ";".join(f"{k:#010x},{a:#010x},{l}" for k, a, l in entries))

# The C++: one array per table ({name, component type, code, 0, 0, 0} entries, a zero name last).
with open("port/src/hook/member_tables.inc", "w") as f:
    f.write("// Generated by port/tools/member_tables.py from upstream's headers (the declarations' addresses and\n// script names) - see exe_data.cpp.\n")
    for name, at, typ, entries in tables:
        f.write(f"// {name}: {len(entries)} member functions\n")
        f.write(f"const MemberEntry kMembers_{at:08X}[] = {{\n")
        for k, a, l in entries:
            f.write(f"    {{{k:#010x}, {typ:#010x}, {a:#010x}, 0, 0, 0}}, // {l}\n")
        f.write("    {0, 0, 0, 0, 0, 0},\n};\n")
    f.write("const MemberTable kMemberTables[] = {\n")
    for name, at, typ, entries in tables:
        f.write(f"    {{{at:#010x}, kMembers_{at:08X}, {len(entries) + 1}}}, // {name}\n")
    f.write("};\n")

# --- the source's own tables: each name's function -------------------------------------------------------------------
cpps = {p: p.read_text(errors="replace") for p in G.rglob("*.cpp")}
hdrs = {p: p.read_text(errors="replace") for p in G.rglob("*.h")}
methods = {}  # "Class::Method" -> address
for t in cpps.values():
    for m in re.finditer(r"REPLACE(?:_SOURCE_ONLY|_UNCHECKED)?\((0x[0-9A-F]{8}),\s*&?([\w:]+)\)", t):
        methods.setdefault("::".join(m.group(2).split("::")[-2:]), int(m.group(1), 16))
member_decl = re.compile(r"^\s*(?:int|bool)\s+(\w+)\(((?:uint32_t\s*\w*,\s*)?(?:Script::)?CStruct\*\s*\w*,\s*(?:Script::)?CScript\*\s*\w*)\)\s*;")
code_range = lambda a: 0x00401000 <= a < 0x00640000
def declarations(text):
    """Each member function declaration: (method, arity, the comment above it plus its trailing one, class)."""
    out, above, cls = [], [], None
    for line in text.splitlines():
        s = line.strip()
        c = re.match(r"(?:class|struct)\s+(\w+)\b[^;]*$", s)
        if c: cls = c.group(1)
        if s.startswith("//"):
            above.append(s[2:].strip()); continue
        m = member_decl.match(line)
        if m:
            trailing = re.search(r"//\s*(.*)$", line)
            arity = 3 if m.group(2).lstrip().startswith("uint32_t") else 2
            out.append((m.group(1), arity, " ".join(above), trailing.group(1) if trailing else "", cls))
            continue  # (a comment above several declarations in a row is theirs too)
        above = []
    return out
def method_address(text, cls, method):
    """The REPLACE address of `method` - of the class being declared, else of any class the header declares."""
    for c in [cls] + re.findall(r"^\s*(?:class|struct)\s+(\w+)", text, re.M):
        if f"{c}::{method}" in methods: return methods[f"{c}::{method}"]
def keys_in(text, keys):
    return [k for k in (int(tok, 16) if tok.startswith("0x") else crc(tok)
                        for tok in re.findall(r"0x[0-9A-F]{8}|[A-Za-z_]\w*", text)) if k in keys]
source_tables = []
for p, t in sorted(cpps.items()):
    for m in re.finditer(r"GAME_GLOBAL\(uint32_t\[\d+\],\s*(g_\w*MemberFunctions),\s*(0x[0-9A-F]{8}),([^;]*)\);", t):
        values = [int(v, 0) for v in re.findall(r"0x[0-9A-Fa-f]+|\b\d+\b", m.group(3))]
        keys = [values[i] for i in range(0, len(values), 6) if values[i]]
        at = int(m.group(2), 16)
        local = [h for h, ht in hdrs.items() if f"0x{at:08X}" in ht or h == p.with_suffix(".h")]
        found, catch, arities = {}, None, set()
        def take(key, address, arity, how):
            if key in keys and key not in found and code_range(address):
                found[key] = (address, arity, how)
        for h in local:
            decls = declarations(hdrs[h])
            for method, arity, above, trailing, cls in decls:
                own = method_address(hdrs[h], cls, method)
                for text in (above, trailing):
                    # "0xADDR [0xKEY, ...]" / "0xADDR (Name, ...)"; "0xADDR (N more names...)": every other name
                    for d in re.finditer(r"(0x[0-9A-F]{8})\s*(\[[^\]]*\]|\([^)]*\))", text):
                        a = int(d.group(1), 16)
                        if re.search(r"\d+ more names", d.group(2)) and code_range(a): catch = (a, arity)
                        for k in keys_in(d.group(2), keys): take(k, a, arity, "doc")
                if not own: continue
                for k in [crc(method), crc("Obj_" + method)] + keys_in(trailing, keys) + keys_in(above.split(":")[0], keys):
                    take(k, own, arity, "decl")
            # "(Name is 0xADDR's ...)": a function folded into another component's
            for d in re.finditer(r"\((\w+) is (0x[0-9A-F]{8})'s", hdrs[h]):
                arity = next((a for _, a, *_ in declarations(hdrs[h])), 2)
                take(crc(d.group(1)), int(d.group(2), 16), arity, "folded")
            # the section's declarations in the table's order, when the counts agree
            section = re.search(r"--- script member functions \(the table at 0x%08X[^\n]*\n(.*?)\n\s*\n" % at, hdrs[h], re.S)
            if section:
                listed = [(method_address(hdrs[h], cls, meth), ar) for meth, ar, _, _, cls in declarations(section.group(1))]
                if len(listed) == len(keys) and all(a for a, _ in listed):
                    for k, (a, ar) in zip(keys, listed): take(k, a, ar, "order")
        # elsewhere: "0xADDR Name" just above (or after) a declaration of the function
        for h, ht in hdrs.items():
            if h in local: continue
            for method, arity, above, trailing, cls in declarations(ht):
                own = method_address(ht, cls, method)
                for text in (above, trailing):
                    d = re.match(r"(0x[0-9A-F]{8})\s+(?:\(not a Ghidra function\)\s+)?(\w+)", text)
                    if d and own == int(d.group(1), 16):
                        take(crc(d.group(2)), own, arity, "named")
        if catch:
            for k in keys:
                if k not in found: found[k] = (catch[0], catch[1], "catch-all")
        arities = {v[1] for v in found.values()}
        if len(arities) > 1: print(f"!! {m.group(1)}: functions with both argument lists", file=sys.stderr)
        missing = [k for k in keys if k not in found]
        print(f"// {m.group(1)} 0x{at:08X}: {len(found)}/{len(keys)}" + (f" (missing {' '.join(f'{k:08X}' for k in missing)})" if missing else ""), file=sys.stderr)
        source_tables.append((m.group(1), at, keys, found))
with open("port/src/hook/member_tables.inc", "a") as f:
    f.write("\n// The source's tables (GAME_GLOBAL): each member function's code, by table and name.\n")
    f.write("const MemberCode kMemberCode[] = {\n")
    for gname, at, keys, found in source_tables:
        f.write(f"    // {gname}\n")
        for k in keys:
            if k in found:
                a, arity, how = found[k]
                f.write(f"    {{{at:#010x}, {k:#010x}, {a:#010x}}}, // {how}, {arity} arguments\n")
    f.write("};\n")
