#!/usr/bin/env python3
"""Give every pure-x87 `__asm { ... }` block in upstream/src/game a portable C++ twin.

The block stays as it is under `#if defined(_M_IX86)`; the `#else` branch is C++ generated by running the block on a
symbolic FPU stack (each value a `double` temporary, so precision is double, not the x87's 64-bit significand). Blocks
with anything besides x87 instructions (calls, register moves, jumps), and blocks inside naked functions, are left for
hand porting and listed.

    python3 -I port/tools/x87_to_cpp.py [--check] [--verbose]
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GAME = ROOT / "upstream" / "src" / "game"
SKIP_FILES = {"x87_math.h"}  # ported by hand
GUARD = "#if defined(_M_IX86) // NOT ORIGINAL: the #else branch is generated by port/tools/x87_to_cpp.py"

ASM_BLOCK = re.compile(r"^([ \t]*)__asm[ \t]*\{[ \t]*(?://[^\n]*)?\n(.*?)^\1\}[ \t]*;?[ \t]*$", re.M | re.S)
ST = re.compile(r"^st(?:\((\d)\))?$")


class Unsupported(Exception):
    pass


class Fpu:
    def __init__(self) -> None:
        self.stack: list[str] = []  # top last
        self.out: list[str] = []
        self.n = 0
        self.status = "0"  # condition codes of the last compare, as an expression

    def temp(self, expr: str) -> str:
        name = f"x87_{self.n}"
        self.n += 1
        self.out.append(f"double {name} = {expr};")
        return name

    def push(self, expr: str) -> None:
        self.stack.append(self.temp(expr))

    def pop(self) -> str:
        if not self.stack:
            raise Unsupported("stack underflow (values from before the block)")
        return self.stack.pop()

    def st(self, i: int) -> str:
        if i >= len(self.stack):
            raise Unsupported("reads a register set before the block")
        return self.stack[-1 - i]

    def set_st(self, i: int, expr: str) -> None:
        if i >= len(self.stack):
            raise Unsupported("writes a register set before the block")
        self.stack[-1 - i] = self.temp(expr)


def memory(operand: str, integer: bool = False) -> tuple[str, str | None]:
    """(lvalue expression, C type of the access) for a memory operand."""
    m = re.match(r"^(byte|word|dword|qword|tbyte)\s+ptr\s+\[\s*([A-Za-z_]\w*)\s*\]$", operand)
    if m:
        size, name = m.groups()
        types = {
            ("word", True): "int16_t", ("dword", True): "int32_t", ("qword", True): "int64_t",
            ("dword", False): "float", ("qword", False): "double",
        }
        t = types.get((size, integer))
        if not t:
            raise Unsupported(f"operand {operand}")
        return f"*reinterpret_cast<{t}*>(&{name})", t
    m = re.match(r"^\[?\s*([A-Za-z_]\w*)\s*\]?$", operand)
    if m and not ST.match(operand):
        return m.group(1), None
    raise Unsupported(f"operand {operand}")


def load(operand: str, integer: bool = False) -> str:
    lvalue, _ = memory(operand, integer)
    return f"static_cast<double>({lvalue})"


def store(fpu: Fpu, operand: str, value: str, integer: bool = False, truncate: bool = False) -> None:
    lvalue, t = memory(operand, integer)
    if integer:  # FIST/FISTP use the rounding control (the default: to nearest), FISTTP truncates
        value = f"std::trunc({value})" if truncate else f"std::nearbyint({value})"
    target = t or f"std::remove_reference_t<decltype({lvalue})>"
    fpu.out.append(f"{lvalue} = static_cast<{target}>({value});")


def register(operand: str) -> int:
    m = ST.match(operand.replace(" ", ""))
    if not m:
        raise Unsupported(f"register {operand}")
    return int(m.group(1) or 0)


ARITH = {"fadd": "{a} + {b}", "fsub": "{a} - {b}", "fsubr": "{b} - {a}", "fmul": "{a} * {b}", "fdiv": "{a} / {b}",
         "fdivr": "{b} / {a}"}


def step(fpu: Fpu, op: str, args: list[str]) -> None:
    if op in ("fld", "fild"):
        if op == "fld" and ST.match(args[0].replace(" ", "")):
            fpu.push(fpu.st(register(args[0])))
        else:
            fpu.push(load(args[0], op == "fild"))
    elif op in ("fld1", "fldz", "fldpi", "fldl2e", "fldl2t", "fldlg2", "fldln2"):
        fpu.push({"fld1": "1.0", "fldz": "0.0", "fldpi": "3.14159265358979323846", "fldl2e": "1.4426950408889634",
                  "fldl2t": "3.3219280948873622", "fldlg2": "0.30102999566398120", "fldln2": "0.69314718055994531"}[op])
    elif op in ("fst", "fstp", "fist", "fistp", "fisttp"):
        if args and ST.match(args[0].replace(" ", "")):
            i = register(args[0])
            if i:
                fpu.set_st(i, fpu.st(0))
        else:
            store(fpu, args[0], fpu.st(0), op.startswith("fi"), op == "fisttp")
        if op.endswith("p"):
            fpu.pop()
    elif op in ("fsin", "fcos", "fsqrt", "fabs", "fchs", "frndint"):
        expr = {"fsin": "std::sin({})", "fcos": "std::cos({})", "fsqrt": "std::sqrt({})", "fabs": "std::fabs({})",
                "fchs": "-{}", "frndint": "std::nearbyint({})"}[op]
        fpu.set_st(0, expr.format(fpu.st(0)))
    elif op == "fsincos":
        a = fpu.st(0)
        fpu.set_st(0, f"std::sin({a})")
        fpu.push(f"std::cos({a})")
    elif op == "fptan":
        fpu.set_st(0, f"std::tan({fpu.st(0)})")
        fpu.push("1.0")
    elif op == "fpatan":
        x = fpu.pop()
        fpu.set_st(0, f"std::atan2({fpu.st(0)}, {x})")
    elif op == "fyl2x":
        x = fpu.pop()
        fpu.set_st(0, f"{fpu.st(0)} * std::log2({x})")
    elif op == "fscale":
        fpu.set_st(0, f"std::ldexp({fpu.st(0)}, static_cast<int>(std::trunc({fpu.st(1)})))")
    elif op == "f2xm1":
        fpu.set_st(0, f"std::exp2({fpu.st(0)}) - 1.0")
    elif op == "fprem":
        fpu.set_st(0, f"std::fmod({fpu.st(0)}, {fpu.st(1)})")
    elif op == "fxch":
        i = register(args[0]) if args else 1
        s = fpu.stack
        if i >= len(s):
            raise Unsupported("fxch past the block's values")
        s[-1], s[-1 - i] = s[-1 - i], s[-1]
    elif op.rstrip("p") in ARITH or (op.startswith("fi") and op[0] + op[2:] in ARITH):
        integer = op.startswith("fi")
        base = (op[0] + op[2:]) if integer else op
        popping = base.endswith("p") and base.rstrip("p") in ARITH
        base = base.rstrip("p") if popping else base
        form = ARITH[base]
        if popping:
            # fop st(i), st: st(i) = st(i) op st(0), then pop (no operands: st(1))
            i = register(args[0]) if args else 1
            fpu.set_st(i, form.format(a=fpu.st(i), b=fpu.st(0)))
            fpu.pop()
        elif len(args) == 2:
            i, j = register(args[0]), register(args[1])
            fpu.set_st(i, form.format(a=fpu.st(i), b=fpu.st(j)))
        elif len(args) == 1 and ST.match(args[0].replace(" ", "")):
            fpu.set_st(0, form.format(a=fpu.st(0), b=fpu.st(register(args[0]))))
        else:
            fpu.set_st(0, form.format(a=fpu.st(0), b=load(args[0], integer)))
    elif op in ("fcom", "fcomp", "fcompp", "fucom", "fucomp", "fucompp", "ftst"):
        a = fpu.st(0)
        if op == "ftst":
            b = "0.0"
        elif not args or ST.match(args[0].replace(" ", "")):
            b = fpu.st(register(args[0]) if args else 1)
        else:
            b = load(args[0])
        # C0 (0x100) below, C2 (0x400) unordered, C3 (0x4000) equal
        fpu.status = fpu.temp(
            f"std::isunordered({a}, {b}) ? 0x4500 : ({a} < {b} ? 0x0100 : 0) | ({a} == {b} ? 0x4000 : 0)")
        if op.endswith("pp"):
            fpu.pop()
            fpu.pop()
        elif op.endswith("p"):
            fpu.pop()
    elif op in ("fnstsw", "fstsw"):
        lvalue, _ = memory(args[0])
        if lvalue in ("ax", "eax"):
            raise Unsupported("status word to a register")
        fpu.out.append(f"{lvalue} = static_cast<uint16_t>({fpu.status});")
    else:
        raise Unsupported(f"instruction {op}")


def translate(body: str) -> list[str]:
    fpu = Fpu()
    for raw in body.split("\n"):
        line = raw.split("//")[0].split(";")[0].strip()
        if not line:
            continue
        parts = line.split(None, 1)
        op = parts[0].lower()
        args = [a.strip() for a in parts[1].split(",")] if len(parts) > 1 else []
        step(fpu, op, args)
    if fpu.stack:
        raise Unsupported(f"leaves {len(fpu.stack)} values on the stack")
    return fpu.out


def in_naked_function(text: str, pos: int) -> bool:
    head = text.rfind("\n}", 0, pos)  # the previous top-level function's end
    return "__declspec(naked)" in text[head if head >= 0 else 0:pos]


def convert(text: str) -> tuple[str, int, list[str]]:
    out, pos, done, left = [], 0, 0, []
    for m in ASM_BLOCK.finditer(text):
        line = text.count("\n", 0, m.start()) + 1
        before = text[:m.start()].rstrip("\n").rsplit("\n", 1)[-1].strip()
        if before.startswith("#if defined(_M_IX86)") or in_naked_function(text, m.start()):
            continue
        try:
            code = translate(m.group(2))
        except Unsupported as e:
            left.append(f"{line}: {e}")
            continue
        indent = m.group(1)
        out.append(text[pos:m.start()])
        out.append(f"{GUARD}\n{m.group(0)}\n#else\n{indent}{{\n" +
                   "\n".join(indent + "    " + c for c in code) + f"\n{indent}}}\n#endif")
        pos = m.end()
        done += 1
    out.append(text[pos:])
    new = "".join(out)
    if done:
        new = add_includes(new, ["<cmath>", "<type_traits>"])
    return new, done, left


def add_includes(text: str, headers: list[str]) -> str:
    """The headers the generated code needs, after the file's last #include."""
    missing = [h for h in headers if f"#include {h}" not in text]
    last = None
    for last in re.finditer(r"^#include [<\"].*$", text, re.M):
        pass
    if not last:  # (a header with no includes: after its #pragma once)
        last = re.search(r"^#pragma once$", text, re.M)
        missing = [""] + missing if last else missing
    if not missing or not last:
        return text
    return text[:last.end()] + "".join(f"\n#include {h}" if h else "\n" for h in missing) + text[last.end():]


def main() -> int:
    check, verbose = "--check" in sys.argv, "--verbose" in sys.argv
    done_total, left_total = 0, 0
    for path in sorted(GAME.rglob("*.cpp")) + sorted(GAME.rglob("*.h")):
        if path.name in SKIP_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        if "__asm" not in text:
            continue
        new, done, left = convert(text)
        done_total += done
        left_total += len(left)
        rel = path.relative_to(ROOT)
        if done or left:
            print(f"{rel}: {done} converted" + (f", {len(left)} left" if left else ""))
            if verbose:
                for l in left:
                    print(f"    {l}")
        if done and not check:
            path.write_text(new, encoding="utf-8")
    print(f"{done_total} blocks {'convertible' if check else 'converted'}, {left_total} left for hand porting")
    return 0


if __name__ == "__main__":
    sys.exit(main())
